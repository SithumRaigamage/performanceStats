#!/usr/bin/env node
// Creates the Ed25519 keypair used to sign licence keys.
//   node licensing/generate-keypair.mjs          (refuses to overwrite)
//   node licensing/generate-keypair.mjs --force  (DANGER: invalidates every key already sold)
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const keysDir = path.join(here, 'keys');
const privFile = path.join(keysDir, 'private.pem');
const pubModule = path.join(here, '..', 'backend', 'src', 'license-public-key.js');

if (fs.existsSync(privFile) && !process.argv.includes('--force')) {
  console.error(`A private key already exists at ${privFile}.\nRegenerating it invalidates every licence key you have issued. Use --force only if you really mean it.`);
  process.exit(1);
}

const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519');
fs.mkdirSync(keysDir, { recursive: true });
fs.writeFileSync(privFile, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
const pubPem = publicKey.export({ type: 'spki', format: 'pem' });
fs.writeFileSync(path.join(keysDir, 'public.pem'), pubPem);
fs.writeFileSync(
  pubModule,
  `// Generated by licensing/generate-keypair.mjs. Public key only, safe to ship.\nexport const PUBLIC_KEY_PEM = \`${pubPem.trim()}\`;\n`
);
console.log(`Private key: ${privFile}  (KEEP SECRET, back it up, never commit)`);
console.log(`Public key embedded in: ${pubModule}`);
